import numpy as np
import pandas as pd
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix
from sklearn.model_selection import train_test_split

class BayesClassifierMF:

    def __init__(self):
        self.classes = None
        self.priors = {}
        self.parameters = {}
        self.features = None


    def gaussian_probability(self, x, mean, variance):
        if variance == 0:
            variance = 1e-10
        exponent = np.exp(-((x - mean) ** 2) / (2 * variance))
        probability = exponent / np.sqrt(2 * np.pi * variance)
        return probability


    def fit(self, X, y):
        self.features = list(X.columns)
        self.classes = np.unique(y)
        total_records = len(y)

        for c in self.classes:

            X_c = X[y == c]


            self.priors[c] = len(X_c) / total_records


            self.parameters[c] = {}
            for f in self.features:
                mean = X_c[f].mean()
                variance = X_c[f].var()
                self.parameters[c][f] = {"mean": mean, "variance": variance}

    def display_priors(self):
        print("\n--- Prior Probabilities ---")
        for c in self.classes:
            print(f"Class {c}: {self.priors[c]:.4f}")


    def display_parameters(self):
        print("\n--- Mean and Variance of Features ---")
        for c in self.classes:
            print(f"\nClass: {c}")
            for f in self.features:
                mean = self.parameters[c][f]["mean"]
                variance = self.parameters[c][f]["variance"]
                print(f"  Feature: {f:<15} | Mean: {mean:<10.4f} | Variance: {variance:.4f}")


    def predict_single(self, row):
        probabilities = {}
        for c in self.classes:
            probability = self.priors[c]
            for f in self.features:
                mean = self.parameters[c][f]["mean"]
                variance = self.parameters[c][f]["variance"]
                likelihood = self.gaussian_probability(row[f], mean, variance)
                probability *= likelihood
            probabilities[c] = probability


        prediction = max(probabilities, key=probabilities.get)
        return prediction


    def predict(self, X):
        predictions = []
        for _, row in X.iterrows():
            pred = self.predict_single(row)
            predictions.append(pred)
        return np.array(predictions)

data=pd.read_csv("/content/heart.csv")

print(data.head())

print(f"\nDataset Shape: {data.shape[0]} rows, {data.shape[1]} columns")

X = data.drop(columns=["target"])

y = data["target"]

print("\nFeature Names:", list(X.columns))
print("Target Classes:", np.unique(y))

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.20, random_state=42, stratify=y
)
print(f"\nTraining Samples: {len(X_train)}, Testing Samples: {len(X_test)}")

model = BayesClassifierMF()

model.fit(X_train, y_train)

model.display_priors()
model.display_parameters()

y_pred = model.predict(X_test)

accuracy = accuracy_score(y_test, y_pred)
cm = confusion_matrix(y_test, y_pred)
report = classification_report(y_test, y_pred)

print("\n--- Model Evaluation ---")
print(f"Accuracy: {accuracy * 100:.2f}%")
print("\nConfusion Matrix:")
print(cm)
print("\nClassification Report:")
print(report)

print("\n--- Enter patient details ---")
user_data = {}
for feature in X.columns:
    val = float(input(f"Enter value for {feature}: "))
    user_data[feature] = val

user_patient = pd.Series(user_data)

patient_pred = model.predict_single(user_patient)

print("\n--- Diagnostic Result ---")
if patient_pred == 1:
    print("Heart Disease Present")
else:
    print("Heart Disease Absent")

