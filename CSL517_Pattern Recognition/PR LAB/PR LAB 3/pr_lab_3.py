# Step 1: Import Required Libraries

import pandas as pd

import numpy as np

from sklearn.model_selection import train_test_split

from sklearn.metrics import accuracy_score, confusion_matrix, classification_report

# Step 2: Define BayesClassifier Class

class BayesClassifier:

    def __init__(self):
        self.classes = None
        self.priors = {}
        self.mean = {}
        self.variance = {}

    def gaussian_probability(self, x, mean, variance):

        if variance == 0:
            variance = 0.000000001

        exponent = np.exp(-((x - mean) ** 2) / (2 * variance))

        probability = exponent / np.sqrt(2 * np.pi * variance)

        return probability

    def fit(self, X, y):

        self.classes = np.unique(y)

        for c in self.classes:

            class_data = X[y == c]

            self.priors[c] = len(class_data) / len(X)

            self.mean[c] = np.mean(class_data)

            self.variance[c] = np.var(class_data)

    def predict(self, x):

        probabilities = {}

        for c in self.classes:

            likelihood = self.gaussian_probability(
                x,
                self.mean[c],
                self.variance[c]
            )

            prior = self.priors[c]

            probabilities[c] = likelihood * prior

        predicted_class = max(
            probabilities,
            key=probabilities.get
        )

        return predicted_class

    def predict_batch(self, X):

        predictions = []

        for x in X:
            predictions.append(self.predict(x))

        return np.array(predictions)

    def display_parameters(self):

        print("Classes:", self.classes)

        for c in self.classes:
            print("\nClass:", c)
            print("Prior:", self.priors[c])
            print("Mean:", self.mean[c])
            print("Variance:", self.variance[c])

diabetes = pd.read_csv("/content/Naive-Bayes-Classification-Data.csv")

diabetes.head()

print("Rows and Columns:", diabetes.shape)

X = diabetes["glucose"].values
y = diabetes["diabetes"].values

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

model = BayesClassifier()

model.fit(X_train, y_train)

model.display_parameters()

y_pred = model.predict_batch(X_test)

accuracy = accuracy_score(y_test, y_pred)

print("Accuracy:", accuracy)
print("Accuracy (%):", accuracy * 100)

cm = confusion_matrix(y_test, y_pred)

print("Confusion Matrix:")
print(cm)

print("Classification Report:")
print(classification_report(y_test, y_pred))

